class VoiceCapabilitiesResponse(BaseModel):
    """Voice capabilities supported across active providers."""
    telephony_providers: List[ProviderCapabilities]
    stt_providers: List[str]
    tts_providers: List[str]
    supported_audio_codecs: List[str]


class SimulateInboundCallRequest(BaseModel):
    """Inbound call simulation payload."""
    called_number: str = Field(..., description="Phone number dialled by customer")
    caller_number: Optional[str] = Field("+919876543210", description="Customer phone number")
    provider_name: str = Field("mock", description="Telephony provider name")
    claimed_business_id: Optional[str] = Field(None, description="Optional claimed business ID for verification")
    metadata: Dict[str, Any] = Field(default_factory=dict)


class SimulateInboundCallResponse(BaseModel):
    """Result of inbound call simulation."""
    session_id: str
    business_id: str
    business_name: str
    greeting_message: str
    status: str
    called_number_masked: str
    caller_number_masked: str


class SimulateTurnRequest(BaseModel):
    """User speech turn simulation payload."""
    text: str = Field(..., description="Customer speech transcription text")
    speaker: str = Field("customer", description="Speaker role")
    is_final: bool = Field(True, description="Whether speech is finalized")


class SimulateTurnResponse(BaseModel):
    """Voice turn response generated by receptionist workflow."""
    session_id: str
    turn_id: str
    user_text: str
    assistant_text: str
    tool_calls_executed: List[str]
    pending_action: Optional[Dict[str, Any]] = None
    session_status: str
    should_terminate: bool


class TerminateSessionRequest(BaseModel):
    """Session termination payload."""
    reason: str = Field("completed", description="Reason for hanging up")
    summary: Optional[str] = Field(None, description="Optional call notes or summary")


class TerminateSessionResponse(BaseModel):
    """Session termination confirmation."""
    session_id: str
    status: str
    duration_seconds: int
    ended_at: Optional[str] = None
    message: str


class VoiceSessionDetailResponse(BaseModel):
    """Detailed view of a voice session and its full message transcript."""
    session_id: str
    business_id: str
    status: str
    provider_name: str
    called_number_masked: str
    caller_number_masked: str
    started_at: Optional[str] = None
    ended_at: Optional[str] = None
    last_turn_at: Optional[str] = None
    messages: List[Dict[str, Any]]



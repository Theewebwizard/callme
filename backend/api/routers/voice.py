@router.websocket("/exotel/ws")
@router.websocket("/ws/exotel")
async def handle_exotel_media_stream(
    websocket: WebSocket,
    call_router: InboundCallRouter = Depends(get_call_router),
    session_manager: VoiceSessionManager = Depends(get_session_manager),
    orchestrator: VoiceTurnOrchestrator = Depends(get_orchestrator),
) -> None:
    """
    Exotel AgentStream bidirectional WebSocket media boundary.
    Handles handshake authentication, event lifecycle (connected, start, media, mark, clear, stop),
    audio format validation, bounded buffering, and dialogue orchestration.
    """
    settings = get_settings()
    provider = get_telephony_provider("exotel")

    global _LAST_CALL_DIAGNOSTICS
    diagnostics = CallDiagnostics()
    _LAST_CALL_DIAGNOSTICS = diagnostics
    diagnostics.record_ws_connected()

    # 1. Handshake Authentication Check (HTTP Basic Auth)
    headers = dict(websocket.headers)
    if settings.ENVIRONMENT == "production":
        # In production, require configured Exotel credentials and strictly verify Basic Auth
        if not settings.is_exotel_configured or not provider.verify_handshake_auth(headers):
            diagnostics.record_ws_authenticated(False)
            logger.warning("Rejected Exotel WebSocket handshake in production: Authentication missing or invalid.")
            await websocket.close(code=status.WS_1008_POLICY_VIOLATION, reason="Unauthorized")
            return
    else:
        if "authorization" in headers:
            # If client passed Authorization header in test/dev, verify it
            if not provider.verify_handshake_auth(headers):
                diagnostics.record_ws_authenticated(False)
                logger.warning("Rejected Exotel WebSocket handshake: Invalid provided Basic Auth.")
                await websocket.close(code=status.WS_1008_POLICY_VIOLATION, reason="Unauthorized")
                return

    diagnostics.record_ws_authenticated(True)
    await websocket.accept()
    logger.info("Exotel AgentStream WebSocket connection accepted.")

    stt_provider = get_stt_provider()
    tts_provider = get_tts_provider()

    session_id: Optional[str] = None
    stream_sid: Optional[str] = None
    business_id: Optional[str] = None
    has_started: bool = False
    audio_buffer = bytearray()
    exotel_sample_rate = settings.EXOTEL_SAMPLE_RATE

    # Real-time streaming & barge-in coordination
    stt_stream: Optional[Any] = None
    cancellation_token = asyncio.Event()
    is_assistant_speaking: bool = False
    last_assistant_speech: str = ""

    try:
        while True:
            # Receive text frame with idle timeout
            try:
                message_text = await asyncio.wait_for(
                    websocket.receive_text(),
                    timeout=float(settings.VOICE_WS_IDLE_TIMEOUT_SECONDS),
                )
            except asyncio.TimeoutError:
                logger.warning("Exotel WebSocket idle timeout (%ss) reached.", settings.VOICE_WS_IDLE_TIMEOUT_SECONDS)
                await websocket.close(code=status.WS_1001_GOING_AWAY, reason="Idle timeout")
                break
            except WebSocketDisconnect:
                logger.info("Exotel WebSocket client disconnected.")
                break

            # Frame size validation
            if len(message_text.encode("utf-8")) > settings.VOICE_WS_MAX_MESSAGE_BYTES:
                logger.warning("Exotel message exceeded maximum frame size (%s bytes).", settings.VOICE_WS_MAX_MESSAGE_BYTES)
                await websocket.close(code=status.WS_1009_MESSAGE_TOO_BIG, reason="Message too large")
                break

            # Parse JSON
            try:
                raw_event = json.loads(message_text)
                event_msg = ExotelWebSocketMessage(**raw_event)
            except Exception as parse_err:
                logger.warning("Malformed Exotel WebSocket JSON: %s", str(parse_err))
                await websocket.close(code=status.WS_1003_UNSUPPORTED_DATA, reason="Malformed JSON")
                break

            event_type = event_msg.event.lower().strip()

            # Lifecycle: 'connected'
            if event_type == "connected":
                logger.info("Exotel AgentStream handshake confirmed: protocol=%s", raw_event.get("protocol"))
                continue

            # Lifecycle: 'start'
            elif event_type == "start":
                if has_started:
                    logger.warning("Duplicate start event received for stream %s; ignoring.", stream_sid)
                    continue

                if not event_msg.start:
                    logger.warning("Exotel start event missing 'start' data payload.")
                    await websocket.close(code=status.WS_1002_PROTOCOL_ERROR, reason="Missing start payload")
                    break

                start_data = event_msg.start
                diagnostics.record_start(start_data.call_sid, start_data.stream_sid)

                # Audio format validation
                is_valid_format, format_err = validate_exotel_audio_format(start_data.media_format)
                if not is_valid_format:
                    logger.warning("Incompatible Exotel audio format: %s", format_err)
                    await websocket.close(code=status.WS_1003_UNSUPPORTED_DATA, reason=format_err)
                    break

                if start_data.media_format and start_data.media_format.sample_rate:
                    exotel_sample_rate = start_data.media_format.sample_rate

                # Tenant resolution from called number
                inbound_event = InboundCallEvent(
                    provider_call_id=start_data.call_sid,
                    provider_name="exotel",
                    called_number=start_data.to,
                    caller_number=start_data.from_,
                    correlation_id=start_data.stream_sid,
                    metadata={
                        "stream_sid": start_data.stream_sid,
                        "account_sid": start_data.account_sid,
                        "custom_parameters": start_data.custom_parameters,
                        "media_format": start_data.media_format.model_dump() if start_data.media_format else {},
                    },
                )

                try:
                    route_res = call_router.route_inbound_call(inbound_event)
                except UnknownTenantError as ute:
                    diagnostics.record_routing(False, error_code="UnknownTenant")
                    logger.warning("Exotel routing rejected unknown tenant: %s", str(ute))
                    await websocket.close(code=4004, reason="Unknown called number")
                    break
                except InactiveTenantError as ite:
                    diagnostics.record_routing(False, error_code="InactiveTenant")
                    logger.warning("Exotel routing rejected inactive tenant: %s", str(ite))
                    await websocket.close(code=4000, reason="Tenant number inactive")
                    break
                except AmbiguousTenantError as ate:
                    diagnostics.record_routing(False, error_code="AmbiguousTenant")
                    logger.warning("Exotel routing rejected ambiguous tenant: %s", str(ate))
                    await websocket.close(code=4009, reason="Ambiguous tenant number")
                    break
                except TenantMismatchError as tme:
                    diagnostics.record_routing(False, error_code="TenantMismatch")
                    logger.warning("Exotel routing rejected tenant mismatch: %s", str(tme))
                    await websocket.close(code=4003, reason="Tenant mismatch")
                    break
                except Exception as e:
                    diagnostics.record_routing(False, error_code="RoutingError")
                    logger.error("Unexpected error routing Exotel call: %s", str(e), exc_info=True)
                    await websocket.close(code=status.WS_1011_INTERNAL_ERROR, reason="Internal routing error")
                    break

                session_id = route_res.session.session_id
                stream_sid = start_data.stream_sid
                business_id = route_res.business["id"]
                has_started = True
                diagnostics.record_routing(True, business_id=business_id)

                # Persist stream_sid correlation in session metadata
                session_manager.update_session_metadata(session_id, {
                    "stream_sid": stream_sid,
                    "account_sid": start_data.account_sid,
                    "media_format": start_data.media_format.model_dump() if start_data.media_format else {},
                })

                # Initialize streaming STT session if supported
                if hasattr(stt_provider, "create_stream"):
                    try:
                        stt_stream = stt_provider.create_stream(
                            session_id=session_id,
                            sample_rate=exotel_sample_rate,
                        )
                        await stt_stream.connect()
                    except Exception as stt_err:
                        logger.warning("Could not open streaming STT session, using fallback: %s", str(stt_err))
                        stt_stream = None

                # Send initial greeting audio back to caller
                if route_res.greeting and tts_provider:
                    greeting_audio = tts_provider.synthesize(route_res.greeting)
                    if greeting_audio:
                        greeting_chunks = chunk_pcm16(greeting_audio, 320, pad=True)
                        for g_chunk in greeting_chunks:
                            g_b64 = base64.b64encode(g_chunk).decode("utf-8")
                            await websocket.send_text(build_exotel_media_message(stream_sid, g_b64))
                        await websocket.send_text(build_exotel_mark_message(stream_sid, "greeting_complete"))

            # Lifecycle: 'media'
            elif event_type == "media":
                if not has_started or not session_id or not stream_sid:
                    logger.warning("Received Exotel media frame before 'start' event.")
                    await websocket.close(code=status.WS_1002_PROTOCOL_ERROR, reason="Media received before start")
                    break

                if not event_msg.media or not event_msg.media.payload:
                    continue

                try:
                    raw_chunk = base64.b64decode(event_msg.media.payload)
                    diagnostics.record_audio_frame(len(raw_chunk))
                except Exception:
                    logger.warning("Failed to decode base64 audio payload.")
                    continue

                # Buffer boundary check to prevent unbounded memory growth
                if len(audio_buffer) + len(raw_chunk) > settings.VOICE_MAX_BUFFER_BYTES:
                    logger.warning("Audio buffer limit reached (%s bytes); discarding buffer.", settings.VOICE_MAX_BUFFER_BYTES)
                    audio_buffer.clear()

                audio_buffer.extend(raw_chunk)

                # Process through streaming STT if stream is active
                if stt_stream is not None:
                    stt_target_rate = getattr(stt_stream, "sample_rate", exotel_sample_rate)
                    stt_chunk = resample_pcm16(raw_chunk, exotel_sample_rate, stt_target_rate)
                    await stt_stream.send_audio(stt_chunk)

                    # Poll STT stream for incoming transcription events
                    transcript = await stt_stream.receive_event(timeout=0.005)
                    if transcript:
                        text_val = transcript.text.strip()
                        # Barge-in detection: Caller started speaking while assistant is outputting audio
                        if not transcript.is_final and text_val:
                            if is_assistant_speaking:
                                diagnostics.record_barge_in()
                                logger.info("Barge-in detected: '%s'. Clearing telecom buffer.", text_val[:30])
                                cancellation_token.set()
                                is_assistant_speaking = False
                                await websocket.send_text(build_exotel_clear_message(stream_sid))

                        # Finalized utterance turn: require both is_final AND speech_final (turn endpointing)
                        elif transcript.is_final and transcript.speech_final and text_val:
                            diagnostics.record_final_transcript(confidence=transcript.confidence, char_count=len(text_val))
                            # Self-playback / acoustic echo defense: reject transcript echoing assistant speech
                            if last_assistant_speech and text_val.lower() == last_assistant_speech.lower() and len(text_val) > 8:
                                logger.warning("Dropped acoustic echo transcript matching assistant output: '%s'", text_val[:30])
                                continue

                            # Halt any existing assistant playback
                            cancellation_token.set()
                            is_assistant_speaking = False
                            cancellation_token = asyncio.Event()

                            turn_result = orchestrator.process_turn(session_id, transcript)
                            diagnostics.record_llm_turn(
                                duration_ms=turn_result.llm_duration_ms or 0.0,
                                tools_called=turn_result.tool_calls_executed,
                            )
                            if turn_result.assistant_text and tts_provider:
                                last_assistant_speech = turn_result.assistant_text.strip()
                                is_assistant_speaking = True
                                import time
                                t_tts_start = time.perf_counter()
                                reply_audio = tts_provider.synthesize(turn_result.assistant_text)
                                tts_dur_ms = (time.perf_counter() - t_tts_start) * 1000
                                if reply_audio and not cancellation_token.is_set():
                                    diagnostics.record_tts_first_chunk(tts_dur_ms, len(reply_audio))
                                    reply_chunks = chunk_pcm16(reply_audio, 320, pad=True)
                                    for r_chunk in reply_chunks:
                                        if cancellation_token.is_set():
                                            logger.info("Outbound audio interrupted by caller barge-in.")
                                            break
                                        r_b64 = base64.b64encode(r_chunk).decode("utf-8")
                                        await websocket.send_text(build_exotel_media_message(stream_sid, r_b64))
                                        await asyncio.sleep(0)  # Yield to event loop for cooperative I/O

                                    if not cancellation_token.is_set():
                                        await websocket.send_text(build_exotel_mark_message(stream_sid, f"turn_{turn_result.turn_id}_complete"))
                                is_assistant_speaking = False

                            if turn_result.should_terminate:
                                term_res = session_manager.terminate_session(session_id, reason="completed")
                                diagnostics.record_termination(persisted=bool(term_res), reason="completed")
                                await websocket.close(code=status.WS_1000_NORMAL_CLOSURE, reason="Call completed")
                                break
                else:
                    # Fallback / batch mode STT processing
                    transcript = stt_provider.transcribe(bytes(audio_buffer))
                    audio_buffer.clear()

                    if transcript and transcript.text.strip():
                        diagnostics.record_final_transcript(confidence=transcript.confidence, char_count=len(transcript.text.strip()))
                        turn_result = orchestrator.process_turn(session_id, transcript)
                        diagnostics.record_llm_turn(
                            duration_ms=turn_result.llm_duration_ms or 0.0,
                            tools_called=turn_result.tool_calls_executed,
                        )
                        if turn_result.assistant_text and tts_provider:
                            import time
                            t_tts_start = time.perf_counter()
                            reply_audio = tts_provider.synthesize(turn_result.assistant_text)
                            tts_dur_ms = (time.perf_counter() - t_tts_start) * 1000
                            if reply_audio:
                                diagnostics.record_tts_first_chunk(tts_dur_ms, len(reply_audio))
                                reply_chunks = chunk_pcm16(reply_audio, 320, pad=True)
                                for r_chunk in reply_chunks:
                                    r_b64 = base64.b64encode(r_chunk).decode("utf-8")
                                    await websocket.send_text(build_exotel_media_message(stream_sid, r_b64))
                                await websocket.send_text(build_exotel_mark_message(stream_sid, f"turn_{turn_result.turn_id}_complete"))

                        if turn_result.should_terminate:
                            term_res = session_manager.terminate_session(session_id, reason="completed")
                            diagnostics.record_termination(persisted=bool(term_res), reason="completed")
                            await websocket.close(code=status.WS_1000_NORMAL_CLOSURE, reason="Call completed")
                            break

            # Lifecycle: 'dtmf'
            elif event_type == "dtmf":
                digit = event_msg.dtmf.digit if event_msg.dtmf else "?"
                logger.info("Received DTMF digit: %s", digit)

            # Lifecycle: 'mark'
            elif event_type == "mark":
                mark_name = event_msg.mark.name if event_msg.mark else "unnamed"
                logger.info("Exotel playback marker reached: %s", mark_name)

            # Lifecycle: 'clear'
            elif event_type == "clear":
                logger.info("Exotel buffer cleared (barge-in)")

            # Lifecycle: 'stop'
            elif event_type == "stop":
                logger.info("Exotel 'stop' event received.")
                if session_id:
                    term_res = session_manager.terminate_session(session_id, reason="caller_hangup")
                    diagnostics.record_termination(persisted=bool(term_res), reason="caller_hangup")
                    orchestrator.release_session_lock(session_id)
                break

            else:
                logger.warning("Unhandled Exotel event type: %s", event_type)

    finally:
        # Clean up streaming STT session
        if stt_stream is not None:
            try:
                await stt_stream.close()
            except Exception:
                pass

        # Clean up session and locks on disconnect
        if session_id:
            term_res = session_manager.terminate_session(session_id, reason="disconnect")
            diagnostics.record_termination(persisted=bool(term_res), reason="disconnect")
            orchestrator.release_session_lock(session_id)

